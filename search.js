// =================================
// LOCAL SEARCH HISTORY
// =================================

function saveSearchHistory(query) {

    let history =
        JSON.parse(

            localStorage.getItem(
                "nexoraSearchHistory"
            )

        ) || [];


    history.unshift(query);


    history =
        history.slice(0, 10);


    localStorage.setItem(

        "nexoraSearchHistory",

        JSON.stringify(history)

    );


    localStorage.setItem(

        "nexoraSearchCount",

        history.length

    );

}


