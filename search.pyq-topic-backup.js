// =================================
// LOAD PYQs

// =================================

async function loadPYQs() {

    if (!pyqSubject || !pyqButton) {
        return;
    }

    const subject =
        pyqSubject.value;

    const exam =
        pyqExam
            ? pyqExam.value
            : "upsc";

    const type =
        pyqType
            ? pyqType.value
            : "prelims";

    const language =
        pyqLanguage
            ? pyqLanguage.value
            : "bilingual";

    const year =
        pyqYear
            ? pyqYear.value
            : "";

    const topic =
        pyqTopic
            ? pyqTopic.value
            : "";


    pyqTestStatus.textContent =
        "Loading UPSC PYQs...";


    try {

        console.log("NEXORA PYQ REQUEST:", subject, exam, type, language, year, topic);
        const response =
            await fetch(
                "/api/pyq?subject=" +
                encodeURIComponent(subject) +
                "&exam=" +
                encodeURIComponent(exam) +
                "&type=" +
                encodeURIComponent(type) +
                "&language=" +
                encodeURIComponent(language) +
                "&year=" +
                encodeURIComponent(year) +
                "&topic=" +
                encodeURIComponent(topic)
            );


        if (!response.ok) {

            throw new Error(
                "Unable to load PYQs."
            );

        }


        const data =
            await response.json();


        if (!data.success) {

            throw new Error(
                data.message ||
                "PYQ loading failed."
            );

        }


        console.log("NEXORA PYQ CHECK:", data.success, data.total, data.questions, data.language);
        displayPYQs(data);


    } catch (error) {

        console.error(
            "NEXORA PYQ Error:",
            error
        );

        pyqTestStatus.textContent =
            error.message ||
            "Unable to load PYQs.";

    }

}



