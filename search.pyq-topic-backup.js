async function searchBestVideo(query) {

    try {

        const baseUrl =
            (window.location.hostname === "localhost" ||
             window.location.hostname === "127.0.0.1")
                ? "http://localhost:5000"
                : "https://nexora-o8wi.onrender.com";

        const response =
            await fetch(
                baseUrl +
                "/api/video?q=" +
                encodeURIComponent(query)
            );

        const data =
            await response.json();

        if (!response.ok || !data.success) {

            throw new Error(
                data.message ||
                "Video search failed"
            );

        }

        console.log(
            "NEXORA Best Video:",
            data.video
        );

        if (data.video) {

            displayBestVideo(
                data.video
            );

        }

    } catch (error) {

        console.error(
            "NEXORA Video Search Error:",
            error
        );

    }

}

